/**
 * Match a query word with our Curated Academic Word Family Lexicon
 */
export function findAcademicWordFamily(queryWord) {
  if (!queryWord) return null;
  const clean = queryWord.trim().toLowerCase();

  // 1. Direct key match (e.g. 'produce')
  if (ACADEMIC_WORD_FAMILIES[clean]) {
    return ACADEMIC_WORD_FAMILIES[clean];
  }

  // 2. Scan all entries to see if queryWord matches any derivative inside
  for (const [root, family] of Object.entries(ACADEMIC_WORD_FAMILIES)) {
    const allWords = [
      family.verb,
      family.noun,
      family.adjective,
      family.adverb,
      family.opposite
    ].join(', ');

    const words = allWords.split(',').map(w => {
      const match = w.match(/^([^(]+)/);
      return (match ? match[1] : w).trim().toLowerCase();
    });

    if (words.includes(clean)) {
      return family;
    }
  }

  return null;
}
